// Compiles the scalar types and the schemas of module.yaml, the manifest of
// the module scflow:core, to src/schemas.generated.ts.
// Run before each build and each test run (see the scripts of package.json).
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { load } from "js-yaml";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const source = join(root, "module.yaml");
const target = join(root, "src", "schemas.generated.ts");

const parsed = load(readFileSync(source, "utf8"));
if (typeof parsed !== "object" || parsed === null || !Array.isArray(parsed.schemas)) {
  throw new Error("module.yaml must be a mapping with a `schemas` list");
}
const scalarTypes = parsed.scalar_types ?? [];

const banner = "// Generated by scripts/build-schemas.mjs from module.yaml. Do not edit.\n";
const body =
  `export const SCALAR_TYPES: Record<string, unknown>[] = ${JSON.stringify(scalarTypes, null, 2)};\n\n` +
  `export const SCHEMA_LIST: Record<string, unknown>[] = ${JSON.stringify(parsed.schemas, null, 2)};\n`;

writeFileSync(target, banner + body);
