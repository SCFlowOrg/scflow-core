import { BUILTIN_SCALAR_TYPES, isBaseScalarType } from "./builtins.js";
import { modelError } from "./errors.js";
import { parseMapType } from "./mapTypes.js";
import type { TypeResolutionContext } from "./schemaProcessing.js";
import type { NormalizedProperty, NormalizedSchema, TransientValue } from "./types.js";

/**
 * Extensions: a schema whose `extension` relation targets another schema adds
 * its properties to that schema, per the parts `relations` (*Extensions*) and
 * `schema_processing` (*Extensions*) of the document `model` in the `core`
 * dataset.
 *
 * Schema Processing generates the properties of an extension schema E on its
 * target T and on every schema extending T, each tagged by the internal
 * constraint `__extension` naming E, so the schema of T lists them. Their
 * values are stored in the instance of E, which has the key of the instance of
 * T. This module holds what only reads or checks a model; `extensionData.ts`
 * holds what reads and writes instances.
 */

/** The name of the extension schema that generated `prop` on its schema, or `undefined` for a property of the schema itself. */
export function extensionOfProperty(prop: NormalizedProperty): string | undefined {
  const tag = prop.constraints.__extension;
  return typeof tag === "string" ? tag : undefined;
}

/** The `extension` relation of `schema`: it is an extension schema when it has one. */
export function extensionRelationOf(schema: NormalizedSchema): NormalizedProperty | undefined {
  return schema.properties.find((p) => p.constraints.extension === true);
}

/** The names of the extension schemas whose properties `schema` carries, in the order of its properties. */
export function extensionNamesOf(schema: NormalizedSchema): string[] {
  const names: string[] = [];
  for (const prop of schema.properties) {
    const name = extensionOfProperty(prop);
    if (name !== undefined && !names.includes(name)) names.push(name);
  }
  return names;
}

/** The properties of `schema` generated by the extension `extensionName`. */
export function propertiesOfExtension(schema: NormalizedSchema, extensionName: string): NormalizedProperty[] {
  return schema.properties.filter((p) => extensionOfProperty(p) === extensionName);
}

/** Whether `prop` belongs to its schema itself rather than being generated on it by an extension. */
export function isOwnProperty(prop: NormalizedProperty): boolean {
  return extensionOfProperty(prop) === undefined;
}

/** The properties an extension schema adds to its target: all its own, except the `extension` relation. */
export function addedProperties(extension: NormalizedSchema): NormalizedProperty[] {
  return extension.properties.filter((p) => p.constraints.extension !== true && p.constraints.__generated !== true);
}

/**
 * Whether the type `typeName` is a schema, as far as `ctx` knows: it is neither a
 * map type, a base or built-in scalar type, nor a scalar type of the model. A
 * schema not yet registered, such as one created later in the same command,
 * reads as a relation type.
 */
export function isRelationType(typeName: string, ctx: TypeResolutionContext): boolean {
  if (parseMapType(typeName) !== null) return false;
  if (isBaseScalarType(typeName) || BUILTIN_SCALAR_TYPES[typeName] !== undefined || ctx.resolveScalarType(typeName) !== undefined) return false;
  return true;
}

/** Constraints an `extension` relation never carries: it is single-valued and has no inverse. */
const FORBIDDEN_ON_EXTENSION_RELATION = ["is_array", "inverse_name", "inverse_is_array", "inverse_is_mandatory", "owns"];

/** Schema constraints incompatible with an extension schema, which has no key of its own and is owned by its target. */
const FORBIDDEN_ON_EXTENSION_SCHEMA = ["shared_by_name", "embedded", "is_root"];

/**
 * Checks the rules a schema with an `extension` relation follows, each breach a
 * `constraint_violation`: one `extension` relation, on a relation property
 * with no inverse and no `is_array`; no other `owner`, no `name` property, no
 * `shared_by_name`, `embedded` or `is_root`; every other property a relation
 * that is not `mandatory`, an array, a map, or a scalar with a `default_value`,
 * and none carrying `inverse_name`, `owns` or `owner`. A schema with no
 * `extension` relation is not checked. Rules that need other schemas (the
 * target, a name shared with it, a relation targeting this schema) are checked
 * where the properties are generated, see `applyExtensions` in `modelUpgrade.ts`.
 */
export function validateExtensionSchema(
  schemaName: string,
  properties: NormalizedProperty[],
  constraints: Record<string, TransientValue>,
  ctx: TypeResolutionContext,
): void {
  const relations = properties.filter((p) => p.constraints.extension === true);
  if (relations.length === 0) return;
  const fail = (message: string): never => {
    throw modelError("constraint_violation", `extension schema "${schemaName}" ${message}`);
  };

  if (relations.length > 1) fail(`has several "extension" relations (${relations.map((p) => p.name).join(", ")}) — at most one is allowed`);
  const relation = relations[0];
  if (!isRelationType(relation.type, ctx)) fail(`has "extension" on "${relation.name}", which is not a relation`);
  for (const constraint of FORBIDDEN_ON_EXTENSION_RELATION) {
    const value = relation.constraints[constraint];
    if (value !== undefined && value !== false) fail(`has "${constraint}" on its "extension" relation "${relation.name}"`);
  }
  for (const constraint of FORBIDDEN_ON_EXTENSION_SCHEMA) {
    if (constraints[constraint] === true) fail(`cannot be "${constraint}" — its instances have the key of the instance they extend`);
  }

  for (const prop of properties) {
    if (prop === relation || prop.constraints.__generated === true) continue;
    if (prop.name === "name") fail(`has a "name" property — its instances have no key of their own`);
    if (prop.constraints.owner === true || prop.constraints.owns === true || typeof prop.constraints.inverse_name === "string") {
      fail(`has "${prop.name}" with "owner", "owns" or "inverse_name" — only its "extension" relation is an ownership relation`);
    }
    if (isRelationType(prop.type, ctx)) {
      if (prop.constraints.mandatory === true) fail(`has "${prop.name}", a mandatory relation, which an extension instance created from defaults cannot fill`);
      continue;
    }
    if (parseMapType(prop.type) !== null || prop.constraints.is_array === true) continue;
    if (prop.default_value === null) fail(`has "${prop.name}" without a "default_value" — every property of an extension has one, or is a relation`);
  }
}
